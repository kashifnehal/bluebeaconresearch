export const COUNTRY_REGION: Record<string, CanonicalRegionId> = {
  ...DATA_MAJORITY,
  ...UN_M49,
  türkiye: DATA_MAJORITY.turkey,
  uae: DATA_MAJORITY["united arab emirates"],
  usa: UN_M49["united states"],
  us: UN_M49["united states"],
  uk: UN_M49["united kingdom"],
};

export function countryRegion(country: string | null | undefined): CanonicalRegionId | null {
  if (country == null) return null;
  const key = country.trim().toLowerCase();
  if (!key) return null;
  return COUNTRY_REGION[key] ?? null;
}
